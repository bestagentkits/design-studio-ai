import { readFile, writeFile, mkdir } from 'node:fs/promises';
import opentype from 'opentype.js';
// Embedded licensed faces keep SVG, sandboxed publication and offline export self-contained.
const families = [['patrick-hand','Patrick Hand'],['noto-sans','Noto Sans'],['lora','Lora'],['roboto-mono','Roboto Mono']];
const metrics = {}, faces = [];
await mkdir('public/fonts', { recursive: true });
for(const [slug,family] of families) {
  const root=`node_modules/@fontsource/${slug}`, widths={};
  const license=await readFile(`${root}/LICENSE`,'utf8');
  faces.push(`/* ${family} — OFL-1.1\n${license}\n*/`);
  for (const subset of ['latin', 'latin-ext', 'vietnamese']) {
    const bytes = await readFile(`${root}/files/${slug}-${subset}-400-normal.woff`);
    const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));
    for (const [code, glyph] of Object.entries(font.tables.cmap.glyphIndexMap)) widths[code] = font.glyphs.get(glyph).advanceWidth / font.unitsPerEm;
    const css = await readFile(`${root}/${subset}-400.css`, 'utf8');
    const range = css.match(/unicode-range: ([^;]+)/)?.[1];
    const woff = await readFile(`${root}/files/${slug}-${subset}-400-normal.woff2`);
    faces.push(`@font-face{font-family:'${family}';font-style:normal;font-weight:400;font-display:swap;src:url(data:font/woff2;base64,${woff.toString('base64')}) format('woff2');${range ? `unicode-range:${range};` : ''}}`);
  }
  metrics[family.toLowerCase()]=widths;
  await writeFile(`public/fonts/${slug}-license.txt`,license);
}
await writeFile('src/shared/diagram-font-data.ts', `// Generated by scripts/build-diagram-font.mjs. Embedded fonts are OFL-1.1.\nexport const diagramFontCss = ${JSON.stringify(faces.join('\n'))};\nexport const diagramFontAdvances: Record<string, Record<string, number>> = ${JSON.stringify(metrics)};\n`);
